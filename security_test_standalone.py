import html
import re

def _deep_html_escape_json_data(data):
    """Copy of the sanitization function from the main application"""
    if isinstance(data, str):
        return html.escape(data)
    if isinstance(data, list):
        return [_deep_html_escape_json_data(item) for item in data]
    if isinstance(data, dict):
        return {key: _deep_html_escape_json_data(value) for key, value in data.items()}
    return data

def _sanitize_external_api_data(data):
    """Copy of the external API sanitization function from the main application"""
    if data is None:
        return ''
    if isinstance(data, str):
        return html.escape(data)
    if isinstance(data, (int, float, bool)):
        return html.escape(str(data))
    if isinstance(data, dict):
        return {key: _sanitize_external_api_data(value) for key, value in data.items()}
    if isinstance(data, list):
        return [_sanitize_external_api_data(item) for item in data]
    # For any other types, convert to string and escape
    return html.escape(str(data))

def test_deep_html_escape():
    """Test the deep HTML escape function"""
    print("Testing _deep_html_escape_json_data function...")
    
    # Test cases with potential XSS payloads
    test_cases = [
        # Simple string XSS
        "<script>alert('xss')</script>",
        
        # Object with XSS
        {
            "dagName": "<img src=x onerror=alert('xss')>",
            "environmentName": "<script>document.location='http://evil.com'</script>"
        },
        
        # Array with XSS
        ["<svg onload=alert('xss')>", "normal_value"],
        
        # Nested structure with XSS
        {
            "request_data": {
                "dagName": "<iframe src=javascript:alert('xss')></iframe>",
                "nested": ["<object data='data:text/html,<script>alert(1)</script>'></object>"]
            }
        }
    ]
    
    for i, test_case in enumerate(test_cases):
        print(f"\nTest case {i+1}:")
        print(f"Input: {test_case}")
        sanitized = _deep_html_escape_json_data(test_case)
        print(f"Sanitized: {sanitized}")
        
        # Verify that dangerous characters are escaped
        sanitized_str = str(sanitized)
        assert '<script>' not in sanitized_str, "Script tags should be escaped"
        assert '<img' not in sanitized_str or '&lt;img' in sanitized_str, "Image tags should be escaped"
        # Note: html.escape() doesn't escape javascript: URLs by design, but the < > are escaped which prevents execution
        print("✓ PASS: Dangerous content properly escaped")

